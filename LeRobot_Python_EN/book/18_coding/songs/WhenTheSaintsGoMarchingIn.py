# Play "When the saints go marching in"

# American popular song
def melody():
    metronome(prestissimo)  # time 4/4
    dynamics(mezza_voce)
    for i in range(2):
        note(octave + C, quarter); note(octave + E, quarter)
        note(octave + F, quarter)
        note(octave + G, whole + quarter)
    for i in range(2):
        note(octave + C, quarter); note(octave + E, quarter)
        note(octave + F, quarter)
        note(octave + G, half)
        note(octave + E, half)
        note(octave + C, half)
        note(octave + E, half)
        note(octave + D, quarter + D)
        rest(quarter_rest); note(octave + E, quarter)
        note(octave + D, quarter)
        note(octave + C, dotted_half)
        note(octave + C, quarter)
        note(octave + E, half); note(octave + G, quarter)
        note(octave + G, quarter)
        note(octave + G, quarter)
        note(octave + F, dotted_half + half)
        note(octave + E, quarter); note(octave + F, quarter)
        note(octave + G, half)
        note(octave + E, half)
        note(octave + C, half)
        note(octave + D, half)
        note(octave + C, whole + quarter)
        for j in range(2):
            note(octave + C, quarter)
            note(octave + E, dotted_eighth)
            note(octave + C, sixteenth)
            note(octave + E, dotted_eighth)
            note(octave + F, sixteenth)
            note(octave + G, quarter); rest(quarter_rest)
            rest(half_rest)
            rest(quarter_rest)
        note(octave + C, quarter)
        note(octave + E, dotted_eighth)
        note(octave + C, sixteenth)
        note(octave + E, dotted_eighth)
        note(octave + F, sixteenth)
        note(octave + G, quarter); note(octave + E, half)
        note(A, quarter)
        note(octave + C, quarter); note(octave + E, half)
        note(octave + E + flat, quarter)
        note(octave + D, whole)
        rest(dotted_eighth_rest)
        note(octave + D + sharp, sixteenth)
        note(octave + E, dotted_eighth)
        note(octave + G, sixteenth)
        note(octave + E, quarter)
        note(octave + D + natural, quarter)
        note(octave + C, half + dotted_quarter)
        note(B, sixteenth); note(octave + C, quarter)
        note(octave + E, half)
        note(octave + G, dotted_quarter)
        note(octave + A, eighth)
        note(octave + G, quarter)
        note(octave + F, dotted_half)
        note(2 * octave + C, quarter); rest(quarter_rest)
        note(octave + E, quarter); note(octave + F, quarter)
        note(octave + G, half)
        note(octave + E, dotted_eighth)
        note(octave + D + sharp, sixteenth)
        note(octave + C, half)
        note(octave + D, half)
        note(octave + C, whole + quarter); rest(quarter_rest)
        rest(half_rest)

melody()
