from LibRobot import *

# Peano curve
def segmentX(n):
    if n > 0:
        segmentX(n - 1)
        fd()
        segmentY(n - 1)
        fd()
        segmentX(n - 1)
        qtr()
        fd()
        qtr()
        segmentY(n - 1)
        fd()
        segmentX(n - 1)
        fd()
        segmentY(n - 1)
        qtl()
        fd()
        qtl()
        segmentX(n - 1)
        fd()
        segmentY(n - 1)
        fd()
        segmentX(n - 1)

def segmentY(n):
    if n > 0:
        segmentY(n - 1)
        fd()
        segmentX(n - 1)
        fd()
        segmentY(n - 1)
        qtl()
        fd()
        qtl()
        segmentX(n - 1)
        fd()
        segmentY(n - 1)
        fd()
        segmentX(n - 1)
        qtr()
        fd()
        qtr()
        segmentY(n - 1)
        fd()
        segmentX(n - 1)
        fd()
        segmentY(n - 1)

